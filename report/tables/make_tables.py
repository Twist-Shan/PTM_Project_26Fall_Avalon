"""Generate LaTeX tables that must stay identical to the code.

  python report/tables/make_tables.py      (from the Project folder; needs z3 for the verdict column)

cases_table.tex : all 44 hand-written test scenarios (avalon/cases.py) with the claim's formalisation,
                  the expected verdict and the verdict Z3 actually returns.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJ = HERE.parents[1]
sys.path.insert(0, str(PROJ / 'avalon'))
from cases import CASES          # noqa: E402
from smt import SMT              # noqa: E402

ROLE = {'merlin': 'Merlin', 'percival': 'Percival', 'servant': 'Servant', 'morgana': 'Morgana',
        'mordred': 'Mordred', 'oberon': 'Oberon', 'minion': 'Minion'}


def seats(ps):
    return r'\{' + ','.join(str(p + 1) for p in ps) + r'\}'


def claim(c):
    t = c['t']
    if t == 'evil':
        return rf'$\mathit{{evil}}_{{{c["p"] + 1}}}$'
    if t == 'good':
        return rf'$\neg\mathit{{evil}}_{{{c["p"] + 1}}}$'
    if t == 'role':
        return rf'$r_{{{c["p"] + 1}}}=\textsc{{{ROLE[c["r"]]}}}$'
    if t == 'atleast':
        return rf'$|{seats(c["ps"])}\cap E|\ge {c["k"]}$'
    if t == 'exactly':
        return rf'$|{seats(c["ps"])}\cap E|= {c["k"]}$'
    if t == 'evil_set':
        return rf'$E={seats(c["ps"])}$'
    if t == 'not':
        inner = claim(c['a'])
        return r'$\neg$(' + inner + ')'
    if t == 'and':
        return r' $\wedge$ '.join(claim(x) for x in c['as'])
    if t == 'fail_by':
        return rf'quest {c["q"]} fails with {c["f"]} Fail'
    if t == 'vote_pass':
        return rf'{c["yes"]} approvals pass'
    if t == 'team_size':
        return rf'team size$_{{q{c["q"]}}}={c["k"]}$'
    raise ValueError(t)


ABBR = {'entailed': 'ent.', 'contradicted': 'con.', 'undetermined': 'und.', 'inconsistent': 'inc.'}
CAT = {'simple': 'simple', 'boundary': 'boundary', 'combination': 'combin.', 'perspective': 'view',
       'inconsistent': 'illegal', 'variant': 'variant'}


def esc(s):
    return s.replace('&', r'\&').replace('%', r'\%').replace('_', r'\_').replace('#', r'\#')


def main():
    smt = SMT()
    rows = []
    for c in CASES:
        got = smt.classify(c['inst'], c['claim'])['label']
        assert got == c['expect'], (c['id'], got)
        claim_tex = claim(c['claim'])
        if len(c['claim'].get('as', [])) > 2:          # four-way conjunction in T22: write it compactly
            claim_tex = r'$\neg\mathit{evil}_i$ for $i\in\{4,\dots,7\}$'
        rows.append(f"{c['id']} & {CAT[c['cat']]} & {esc(c['text'])} & {claim_tex} & "
                    f"\\texttt{{{esc(', '.join(c['rules']))}}} & {ABBR[c['expect']]} \\\\")
    body = '\n'.join(rows)
    tex = r"""% generated by report/tables/make_tables.py from avalon/cases.py -- do not edit by hand
\begingroup\scriptsize
\setlength{\tabcolsep}{2.6pt}\renewcommand{\arraystretch}{1.18}
\begin{longtable}{@{}l l p{4.25cm} p{2.5cm} p{1.65cm} l@{}}
\caption{All 44 hand-written test scenarios, quoted as written (in Chinese) in \texttt{avalon/cases.py}.
\emph{Claim} is the formalised conclusion ($E$: the set of evil seats; $r_i$: the role of seat $i$; seats are 1-based).
\emph{Exp.} is the verdict derived by hand from the rulebook; Z3 and the independent oracle return exactly this
verdict for every row.}\label{tab:cases}\\
\toprule
ID & Kind & Scenario and question (verbatim) & Claim & Clauses & Exp.\\
\midrule\endfirsthead
\toprule
ID & Kind & Scenario and question (verbatim) & Claim & Clauses & Exp.\\
\midrule\endhead
\bottomrule\endfoot
""" + body + "\n\\end{longtable}\\endgroup\n"
    (HERE / 'cases_table.tex').write_text(tex, encoding='utf-8')
    print('cases_table.tex:', len(rows), 'rows, all verdicts match')

    # prompts, verbatim from the code that produced the runs
    from llm_run import RULE_CARD, TASK, ANSWER, EXTRACT_SYS, EXTRACT_EXAMPLE_IN, EXTRACT_EXAMPLE_OUT, REVEAL_Q
    from followup import FORCE, REPAIR_TAIL

    def verb(title, text):
        return (f'\\paragraph{{{title}}}\n\\begin{{Verbatim}}[breaklines,breakanywhere,fontsize=\\scriptsize,'
                f'frame=single,rulecolor=\\color{{black!25}},framesep=4pt]\n{text.strip()}\n\\end{{Verbatim}}\n')
    parts = [verb('System prompt for direct answers and thinking (rule card + task)', RULE_CARD + '\n\n' + TASK),
             verb('Answer instruction appended to every question', ANSWER),
             verb('Extraction system prompt (followed by one worked example)', EXTRACT_SYS),
             verb('The worked extraction example: input', EXTRACT_EXAMPLE_IN),
             verb('The worked extraction example: output', EXTRACT_EXAMPLE_OUT),
             verb('Reveal-set question', REVEAL_Q),
             verb('Budget-forcing suffix (appended to an unfinished thinking trace)', FORCE),
             verb('Extraction-repair instruction (after the solver-reported conflict)', REPAIR_TAIL)]
    (HERE / 'prompts_appendix.tex').write_text(
        '% generated by report/tables/make_tables.py from avalon/llm_run.py and avalon/followup.py\n'
        + '\n'.join(parts), encoding='utf-8')
    print('prompts_appendix.tex written')


if __name__ == '__main__':
    main()
